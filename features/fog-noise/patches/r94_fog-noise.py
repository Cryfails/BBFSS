# r94_fog-noise (.fixed.py, review 2026-11-15: log prefix, README rule-7 text, cost range; the
# edits and new files are otherwise the draft's): FEATURE patch (order item 5 "Fog noise"; owner: "Fog and wind go by cloud
# direction"). The engine's own sun/moon fog (volumetric_light.comp's march) gets a real 3D noise
# density: uneven, world anchored patches with large and small scales (three octaves of value
# noise from a 32-bit integer hash, no texture), standing still without wind and drifting with
# the wind's direction and speed (gusts included) when BB_WIND=1 (r82's shared wind). Off by
# default behind BB_FOG_NOISE (environment, read once); no ini key yet (rule 4: env for work in
# progress). Cloud direction: nothing in the engine reads the sky's clouds yet (r82's finding), so
# the noise follows the wind, whose direction is BB_WIND_DIR; when the wind follows the clouds,
# so will this.
#
# Decision: NEW builds (NOISE), not r82's WIND builds. The WIND builds stay byte for byte as they
# are (r82's look, its contrast knob and its extinction rule unchanged), WIND has no AREA build
# (r82 refuses AREA+WIND), and its push block has no room for three octaves' offsets and the
# shaping. NOISE builds exist for every march the sun fog has: plain, GATE (r51b ray traced
# gate), AREA (r81 area light gate) and GATE+AREA (r85), each INTEGRATE and REPAIR: 8 builds,
# made lazily per (gated, area) pair at that pair's first march with the noise (usually 2 of 8).
# A march with the noise binds the NOISE build of the pass it would bind and pushes 128 bytes
# (Params + VolumetricFogNoise::Tail: the camera's view to world rows, each octave's offset in
# lattice cells, amplitude, gain, 1 / scale). With BB_WIND=1 the noise's offsets move with the
# wind and the NOISE build takes the place of r82's WIND build for that march (SetFogNoise takes
# back SetWind's request), so BB_FOG_NOISE + BB_WIND drift on EVERY march, area gate marches
# included (r82 excludes those: this closes that gap whenever the noise is on). With BB_WIND
# alone nothing changes (r82 as before). A march the gate view draws (GATE_VIEW) takes no noise.
#
# Mean brightness: m = 1 + a clamp(2 g d, -1, 1) is odd in d around 1 and d (the octaves'
# weighted sum of N - 0.5) is symmetric around 0, so the mean of m is 1. The march multiplies a
# lit sample's in-scattered light by m and keeps the extinction at the mean density
# (exp(-density t) unchanged): the fog's mean light stays the plain march's. CPU probe (S/
# r94_fog-noise_work/probe.py, deleted with the work folder; numbers in the context file): ray
# light noise/plain over 2500 rays of 32 steps over 40 m: mean 1.006 / sd 0.25 at strength 1,
# 1.000 / 0.40 at 3; a 6 m sun shaft: 1.006 / 0.45 and 0.983 / 0.73. Letting the extinction
# follow m (r82's rule) would dim the mean by 1.5-5% (0.985 at 1, 0.956 at 3). Because a sample
# in shadow adds no light, taking m only where lit is exact here (no lit-only approximation).
#
# Cost per march step: unlit (shadowed or skipped by the gate): one compare. Lit: the world
# point (3 dot), 2 or 3 octaves of 8 hashed corners (lowbias32, about 8 integer ops each) and a
# trilinear quintic interpolation (about 50 float ops), the shaping (4 ops): about 300 to 450 ALU
# operations, no memory read, no exp. Estimate at 4K output with 1080p internal (the march is
# 960x540, 32 steps, 16.6 M samples): 0.1 ms with half of them lit, up to 0.4 ms where nearly all
# are lit (outdoors) and lit and shut samples share a warp (NOT measured: read
# "Lighting: volumetric sunlight", EffectPass::Mark 7, with BB_GPU_PROFILE=1, against the same
# build without BB_FOG_NOISE). Memory: no image, no buffer, no upload; up to 8 compute pipelines
# (usually 2) and 252 KB more SPIR-V in the binary (8 builds of 28-36 KB). Kept low by: noise only on lit samples,
# the finest octave dropped past 2.4 scales (24 m at the default 10 m), the march's own dispatch
# at half resolution (no extra pass), a hash instead of a texture.
#
# Off (the default, BB_FOG_NOISE unset/0 and BB_FOG_NOISE_SHOW not 1): bit-identical picture and
# nothing created: VolumetricLight::FogNoiseKnob() (a static guard and a bool) is false, so the
# rasterizer never calls SetFogNoise; fog_noise.on stays false; FogNoiseMarch returns false at
# its first test, so NoisePasses (the only place a NOISE pipeline is made) never runs; the march
# binds the build it bound before and pushes the same bytes (PushBlock holds WindParams or Params
# as r82's wind_push did; push_size is unchanged off). All existing volumetric_light builds
# compile to the same SPIR-V words (proved, see the context file). On the CPU off: one static
# guard + bool test per march, the integrate lambda captures 128 bytes for the push block
# instead of 112. One log line per run: "Volumetric lighting (r94): fog noise off ...".
#
